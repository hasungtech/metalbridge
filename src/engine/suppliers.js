export function catOf(g){
  var t=(g||'').toUpperCase();
  if(/STS|SUS|2205|2507|310S|309S/.test(t)) return '스테인리스';
  if(/TI\s?GR|인코넬|하스텔로이|모넬|INCONEL/.test(t)) return '티타늄·니켈';
  if(/C\d{3,4}|황동|인청동/.test(t)) return '구리·동합금';
  if(/AA?\d{4}|2024|7075|2017|5052|6061|1050/.test(t)) return '알루미늄';
  if(/SKD|SKH|SKS/.test(t)) return '공구강';
  if(/S690|A709/.test(t)) return '고장력강';
  if(/SCM|SNCM|S45C|SM45/.test(t)) return '특수강';
  if(/S355|SAE|SM\d|SS\d|STK|HE\s?\d/.test(t)) return '구조용강';
  return '구조용강';
}
function urgent(){ return /2주|급구|즉시/.test(S.ANS.due||''); }
export function matchSuppliers(){
  var byCat={}, shapeByCat={};
  S.ITEMS.forEach(function(it){
    var k=catOf((it.grades||[]).join(' '));
    (byCat[k]=byCat[k]||[]).push(it.no);
    (shapeByCat[k]=shapeByCat[k]||{})[it.shape]=true;
  });
  var out=[];
  SUPPLIER_MASTER.forEach(function(sp){
    var hit=sp.cat.filter(function(k){ return byCat[k]; });
    if(!hit.length) return;
    var nums=[]; hit.forEach(function(k){ nums=nums.concat(byCat[k]||[]); });
    nums.sort(function(a,b){return a-b;});
    var score=62, shapeOk=false;
    hit.forEach(function(k){
      Object.keys(shapeByCat[k]||{}).forEach(function(sh){
        if(sp.sh.indexOf(sh)>=0) shapeOk=true;
      });
    });
    if(shapeOk) score+=16;
    if(sp.pri===1) score+=12; else if(sp.pri===2) score+=6;
    if(urgent() && sp.c==='한국') score+=8;
    if(urgent() && sp.c!=='한국') score-=12;
    if(/kg|개|매|본/.test(sp.moq)) score+=6;
    score=Math.max(42,Math.min(97,score));
    out.push({sp:sp, cats:hit, items:nums, shapeOk:shapeOk, score:score});
  });
  out.sort(function(a,b){ return b.score-a.score || a.sp.pri-b.sp.pri; });
  return out;
}
export function coverage(){
  var cats={};
  S.ITEMS.forEach(function(it){ cats[catOf((it.grades||[]).join(' '))]=true; });
  var rows=[];
  Object.keys(cats).forEach(function(k){
    var list=SUPPLIER_MASTER.filter(function(sp){ return sp.cat.indexOf(k)>=0; });
    var byC={}; list.forEach(function(sp){ byC[sp.c]=(byC[sp.c]||0)+1; });
    rows.push({cat:k, total:list.length,
      dist:Object.keys(byC).map(function(c){return c+' '+byC[c];}).join(' · '),
      dom:list.filter(function(sp){return sp.c==='한국';}).length});
  });
  return rows;
}
